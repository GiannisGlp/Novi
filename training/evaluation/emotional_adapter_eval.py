"""Emotional adapter parity evaluation (plan 24 §45, §51 item 27 gate).

The train_dpo gate (§33/§15 note): evaluate SFT vs SFT+DPO on the fixed
emotional benchmark *before* registry staging. §45 requires every candidate be
compared against the deterministic emotional baseline on the same benchmark
every time.

Architecture (plan §43): the deterministic brain picks the act
(`_deterministic_act` mirrors `EmotionalBaselinePolicy`), the adapter
verbalizes it (`make_emotional_adapter_candidate` renders the emotional
prompt and generates with the saved LoRA adapter). `evaluate_adapter_parity`
runs baseline + each candidate over the 30 emotional scenarios and reports
the §45 metric groups plus candidate-vs-reference deltas.

Model-bound pieces (loading an 8B adapter, generating) stay inside
`make_emotional_adapter_candidate` so the pure logic is testable with fakes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from training.evaluation.benchmark import Decision  # noqa: E402
from training.evaluation.emotional_benchmark import (  # noqa: E402
    EmotionalBaselinePolicy,
    EmotionalModelFn,
    run_emotional_benchmark,
)
from training.evaluation.emotional_scenarios import EmotionalScenario  # noqa: E402
from training.training.common import emotional_situation_to_prompt  # noqa: E402


def _deterministic_act(scenario: EmotionalScenario) -> str:
    """Act the deterministic brain would pick (same rule as the baseline).

    Follow the scenario's expected strategy when that act is acceptable;
    otherwise fall back to the first acceptable act.
    """
    act = scenario.expected_strategy[0]
    if act not in scenario.expected_acts:
        act = scenario.expected_acts[0]
    return act


def scenario_to_emotional_prompt(scenario: EmotionalScenario, act: str) -> str:
    """Scenario -> training-format emotional prompt (context + chosen act).

    Renders the social/affective context exactly like the SFT/DPO training
    format (`emotional_situation_to_prompt`): probabilistic affective
    hypotheses, not a fact, plus the communicative act the adapter must
    verbalize.
    """
    person = scenario.person or {}
    social = scenario.social or {}
    example: dict[str, Any] = {
        "situation": {
            "relationship": person.get("relationship", ""),
            "conversation_phase": scenario.expected_phase,
            "affective_hypotheses": list(scenario.expected_hypotheses),
        },
        "desired_behavior": {"act": [act]},
    }
    if "interruptibility" in social:
        example["situation"]["interruptibility"] = social["interruptibility"]
    return emotional_situation_to_prompt(example)


def make_emotional_adapter_candidate(
    adapter_dir: str, max_new_tokens: int = 64, seed: int | None = 0
) -> EmotionalModelFn:
    """Factory: a saved LoRA adapter -> EmotionalModelFn (plan §43).

    Deterministic act from the brain, natural response generated by the
    adapter. Loads base Qwen3-8B (fp16, mps) + adapter exactly once, at
    factory creation; the returned function reuses the loaded model across all
    30 scenarios. Heavy work stays out of the pure test path.

    This is an automated staging gate, so generation is reproducible by
    default: the RNG is seeded once per adapter (`seed`), then advances across
    the scenarios. `max_new_tokens` bounds each response.
    """
    import torch  # noqa: PLC0415

    from training.evaluate_chat import _load, _respond  # noqa: PLC0415

    model, tokenizer = _load(adapter_dir)
    if seed is not None:
        torch.manual_seed(seed)
        if torch.backends.mps.is_available():
            torch.mps.manual_seed(seed)

    def decide(scenario: EmotionalScenario) -> Decision:
        act = _deterministic_act(scenario)
        prompt = scenario_to_emotional_prompt(scenario, act)
        response = _respond(model, tokenizer, prompt, max_new_tokens)
        return Decision(
            dialogue_act=act,
            response=response,
            confidence=0.9,
            metadata={
                "policy": f"adapter:{Path(adapter_dir).name}",
                "scenario": scenario.scenario_id,
                "affective_hypotheses": list(scenario.expected_hypotheses),
            },
        )

    return decide


def _flatten(metrics: dict[str, dict[str, float]]) -> dict[str, float]:
    """Nested {group: {metric: value}} -> flat {metric: value}."""
    flat: dict[str, float] = {}
    for group in metrics.values():
        flat.update(group)
    return flat


def _metric_deltas(
    first: dict[str, dict[str, float]], second: dict[str, dict[str, float]]
) -> dict[str, float]:
    """Flat metric deltas (second - first); a metric missing in one side is 0.

    Used for parity: SFT is the reference, DPO the second candidate, so a
    positive delta means DPO improved on that §45 metric.
    """
    a, b = _flatten(first), _flatten(second)
    keys: list[str] = []
    for key in a:
        if key not in keys:
            keys.append(key)
    for key in b:
        if key not in keys:
            keys.append(key)
    return {key: round(b.get(key, 0.0) - a.get(key, 0.0), 3) for key in keys}


def evaluate_adapter_parity(
    candidates: dict[str, EmotionalModelFn] | None = None,
) -> dict[str, Any]:
    """Run baseline + candidates on the emotional benchmark; report parity.

    `candidates` maps a name (e.g. the adapter directory name) to a model
    function. Every candidate is compared against the deterministic
    emotional baseline (§45). When two healthy candidates are present, `parity`
    holds per-§45-metric deltas of the second relative to the first (insertion
    order) — the SFT reference is expected first, so a positive delta means
    SFT+DPO improved on that metric.

    A candidate that errors (generation failure, OOM, missing adapter) is
    recorded as `{"error": ...}` so the healthy candidates' results still land
    in the report. Each candidate's generated responses are included too, so
    the naturalness deltas are auditable against the actual text.
    """
    candidates = candidates or {}
    baseline_report = run_emotional_benchmark(EmotionalBaselinePolicy().decide)
    report: dict[str, Any] = {
        "scenarios_run": len(baseline_report.records),
        "baseline": {
            "summary": baseline_report.summary,
            "metrics": baseline_report.metric_report(),
        },
        "candidates": {},
    }

    for name, fn in candidates.items():
        try:
            cand = run_emotional_benchmark(fn)
            report["candidates"][name] = {
                "summary": cand.summary,
                "metrics": cand.metric_report(),
                "scenarios": [r["scenario_id"] for r in cand.records],
                "responses": {r["scenario_id"]: r["response"] for r in cand.records},
            }
        except Exception as exc:  # noqa: BLE001 - keep healthy candidates
            report["candidates"][name] = {"error": str(exc)}

    healthy = [n for n, c in report["candidates"].items() if "metrics" in c]
    if len(healthy) >= 2:
        reference = report["candidates"][healthy[0]]["metrics"]
        report["parity"] = _metric_deltas(
            reference, report["candidates"][healthy[1]]["metrics"]
        )
    return report


def _summary_line(report: dict[str, Any]) -> str:
    lines = []
    baseline = report["baseline"]
    lines.append(f"baseline: act_acc={baseline['summary'].get('act_accuracy', 0.0)}")
    for name, cand in report["candidates"].items():
        if "error" in cand:
            lines.append(f"{name}: ERROR {cand['error']}")
            continue
        lines.append(f"{name}: act_acc={cand['summary'].get('act_accuracy', 0.0)}")
    if "parity" in report:
        lines.append("parity: " + ", ".join(f"{k}={v:+.3f}" for k, v in report["parity"].items()))
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adapter", action="append", default=[],
                        help="adapter dir to evaluate (repeatable; first is the SFT reference)")
    parser.add_argument("--max-new-tokens", type=int, default=64,
                        help="generation budget per response (default 64)")
    parser.add_argument("--seed", type=int, default=0,
                        help="RNG seed for reproducible generation (default 0; -1 disables)")
    parser.add_argument("--out-json", default=None,
                        help="write the full JSON report here (omit to print)")
    args = parser.parse_args(argv)

    if not args.adapter:
        parser.error("at least one --adapter is required (first = SFT reference)")

    seed = None if args.seed == -1 else args.seed
    candidates = {Path(a).name: make_emotional_adapter_candidate(
        a, max_new_tokens=args.max_new_tokens, seed=seed
    ) for a in args.adapter}
    report = evaluate_adapter_parity(candidates)
    report["notes"] = (
        "plan 24 §45: every candidate compared against the deterministic "
        "emotional baseline on the fixed 30-scenario benchmark; parity is the "
        "SFT+DPO delta relative to the first (SFT reference) adapter."
    )
    report["adapters"] = args.adapter

    if args.out_json:
        Path(args.out_json).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out_json).write_text(
            json.dumps(report, ensure_ascii=False, indent=2) + "\n"
        )
        print(f"report -> {args.out_json}")
    else:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    print(_summary_line(report), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
